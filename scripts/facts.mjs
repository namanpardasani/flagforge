// Counts the facts the landing page states, from the repository itself, so they are never guessed.
//
//   node scripts/facts.mjs            prints the numbers
//   node scripts/facts.mjs --write    also rewrites apps/web/src/landing/facts.ts
//
// Tests are counted by RUNNING each package's suite (the server's needs PostgreSQL and Redis up).
// Routes are counted from the route files: one per router.get/post/put/patch/delete call.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const routesDir = join(root, "apps/server/src/routes");
let routes = 0;
for (const file of readdirSync(routesDir)) {
  const source = readFileSync(join(routesDir, file), "utf8");
  routes += [...source.matchAll(/\brouter\.(get|post|put|patch|delete)\(/g)].length;
}

const packages = ["packages/core", "packages/sdk", "apps/server", "apps/web", "apps/demo"];
const tests = {};
for (const pkg of packages) {
  // The result goes to a file: it is the reliable way to get vitest's JSON report.
  const dir = mkdtempSync(join(tmpdir(), "facts-"));
  const file = join(dir, "report.json");
  try {
    execFileSync("npx", ["vitest", "run", "--reporter=json", `--outputFile=${file}`], { cwd: join(root, pkg), stdio: "ignore" });
  } catch {
    // A failing suite still writes its report; it is checked just below.
  }
  const json = JSON.parse(readFileSync(file, "utf8"));
  rmSync(dir, { recursive: true, force: true });
  if (json.numFailedTests > 0) throw new Error(`${pkg} has ${json.numFailedTests} failing tests: not counting a broken suite`);
  tests[pkg] = json.numPassedTests;
}
const total = Object.values(tests).reduce((a, b) => a + b, 0);
const facts = { tests: total, testsByPackage: tests, routes, packages: packages.length, roles: 4, date: new Date().toISOString().slice(0, 10) };
console.log(JSON.stringify(facts, null, 2));

if (process.argv.includes("--write")) {
  writeFileSync(
    join(root, "apps/web/src/landing/facts.ts"),
    `// Generated by scripts/facts.mjs on ${facts.date}. Do not edit by hand: run \`node scripts/facts.mjs --write\`.
// These are counted from the repository (tests are counted by running each suite), not estimated.
export const FACTS = ${JSON.stringify({ tests: total, routes, packages: packages.length, roles: 4 }, null, 2)} as const;
`,
  );
}
